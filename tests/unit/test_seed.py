"""Tests for the demo dataset seeder (jackrabbit.seed).

The seeder exists so the app can be exercised end-to-end without hand-made
junk in data/jackrabbit.db, so the properties that matter are: it covers every
screen-relevant state, it is idempotent, and it never fakes a status (states are
reached through the guarded transitions, which is what produces audit history).
"""

from datetime import date, datetime, time, timedelta

import pytest
from jackrabbit.models import (
    LinkType,
    Project,
    Ticket,
    TicketLink,
    TicketStatus,
    TicketType,
    Transition,
)
from jackrabbit.seed import DEMO_NOTE, seed_demo_data
from sqlalchemy.pool import StaticPool
from sqlmodel import Session, create_engine, select


@pytest.fixture
def session():
    """In-memory database with the real schema and the UNS system project."""
    from jackrabbit.models import SQLModel

    engine = create_engine(
        "sqlite://",
        connect_args={"check_same_thread": False},
        poolclass=StaticPool,
    )
    SQLModel.metadata.create_all(engine)
    with Session(engine) as seed_session:
        seed_session.add(
            Project(prefix="UNS", name="Unsorted", description="Default", is_system=True)
        )
        seed_session.commit()
    with Session(engine) as working:
        yield working
    engine.dispose()


def _statuses(session: Session) -> set[str]:
    return set(session.exec(select(Ticket.status)).all())


def _types(session: Session) -> set[str]:
    return set(session.exec(select(Ticket.type)).all())


def _by_title(session: Session, title: str) -> Ticket:
    ticket = session.exec(select(Ticket).where(Ticket.title == title)).first()
    assert ticket is not None, f"seed did not create {title!r}"
    return ticket


def _project(session: Session, prefix: str) -> Project:
    project = session.exec(select(Project).where(Project.prefix == prefix)).first()
    assert project is not None, f"seed did not create project {prefix}"
    return project


class TestSeedCoverage:
    def test_creates_projects_and_sprints(self, session: Session) -> None:
        result = seed_demo_data(session)

        assert sorted(result.projects) == ["API", "MSC", "WEB"]
        assert len(result.sprints) == 3
        for prefix in ("WEB", "API", "MSC", "UNS"):
            assert _project(session, prefix)

    def test_covers_every_status_and_type(self, session: Session) -> None:
        seed_demo_data(session)

        assert _statuses(session) == {status.value for status in TicketStatus}
        assert _types(session) == {ticket_type.value for ticket_type in TicketType}

    def test_statuses_are_reached_through_real_transitions(self, session: Session) -> None:
        """Guarded fields must be populated and history recorded, not faked."""
        seed_demo_data(session)

        groomed = _by_title(session, "Add SSO login")
        assert groomed.status == TicketStatus.GROOMED
        assert groomed.approach and groomed.files_to_change
        assert groomed.test_plan and groomed.validation_steps

        in_progress = _by_title(session, "Show session timeout banner")
        assert in_progress.status == TicketStatus.IN_PROGRESS
        assert in_progress.branch_name, "branch name is generated by the transition itself"

        review = _by_title(session, "Send password reset email")
        assert review.status == TicketStatus.READY_FOR_REVIEW
        assert review.pr_url and review.pr_url.startswith("https://")

        complete = _by_title(session, "Export billing history")
        assert complete.status == TicketStatus.COMPLETE
        assert complete.completed_at is not None

        rejected = _by_title(session, "Deprecate v0 endpoints")
        assert rejected.status == TicketStatus.REJECTED

        history = session.exec(select(Transition).where(Transition.ticket_id == complete.id)).all()
        assert [t.to_status for t in history] == [
            TicketStatus.GROOMED.value,
            TicketStatus.IN_PROGRESS.value,
            TicketStatus.READY_FOR_REVIEW.value,
            TicketStatus.COMPLETE.value,
        ]

    def test_epic_has_child_links(self, session: Session) -> None:
        seed_demo_data(session)
        epic = _by_title(session, "Customer portal revamp")

        children = session.exec(
            select(TicketLink).where(
                TicketLink.source_id == epic.id, TicketLink.link_type == LinkType.PARENT
            )
        ).all()
        assert len(children) == 4

    def test_blocking_and_relating_links_exist(self, session: Session) -> None:
        seed_demo_data(session)
        bug = _by_title(session, "Recurring invoice total is wrong")
        blocked = _by_title(session, "Add invoice PDF preview")

        link = session.exec(
            select(TicketLink).where(
                TicketLink.source_id == bug.id, TicketLink.link_type == LinkType.BLOCKS
            )
        ).first()
        assert link is not None and link.target_id == blocked.id

    def test_sprints_are_dated_relative_to_today(self, session: Session) -> None:
        seed_demo_data(session)
        from jackrabbit.models import Sprint

        sprints = session.exec(select(Sprint).order_by(Sprint.planned_start)).all()
        today = datetime.combine(date.today(), time(12, 0))
        assert sprints[0].planned_start <= today <= sprints[0].planned_end
        assert sprints[0].actual_start is not None, "the current sprint has started"
        assert sprints[1].planned_start > today
        assert sprints[2].planned_start > sprints[1].planned_start

    def test_assigned_and_unassigned_tickets_both_exist(self, session: Session) -> None:
        seed_demo_data(session)
        assigned = session.exec(select(Ticket).where(Ticket.sprint_id.is_not(None))).all()  # type: ignore[union-attr]
        unassigned = session.exec(select(Ticket).where(Ticket.sprint_id.is_(None))).all()  # type: ignore[arg-type]
        assert assigned and unassigned

    def test_one_ticket_has_been_moved_between_projects(self, session: Session) -> None:
        seed_demo_data(session)
        moved = _by_title(session, "Investigate flaky backlog filter test")

        assert moved.project_id == _project(session, "WEB").id
        assert moved.original_id and moved.original_id.startswith("MSC-")

    def test_every_seeded_ticket_is_marked(self, session: Session) -> None:
        seed_demo_data(session)
        descriptions = session.exec(select(Ticket.description)).all()
        assert descriptions and all(DEMO_NOTE in text for text in descriptions)


class TestSeedIdempotent:
    def test_second_run_creates_nothing(self, session: Session) -> None:
        first = seed_demo_data(session)
        counts_after_first = (
            len(session.exec(select(Ticket)).all()),
            len(session.exec(select(Project)).all()),
            len(session.exec(select(TicketLink)).all()),
        )

        second = seed_demo_data(session)

        assert first.changed is True
        assert second.changed is False
        assert second.summary() == "Demo data already present - nothing to do."
        assert counts_after_first == (
            len(session.exec(select(Ticket)).all()),
            len(session.exec(select(Project)).all()),
            len(session.exec(select(TicketLink)).all()),
        )

    def test_repeated_runs_do_not_duplicate_transition_history(self, session: Session) -> None:
        seed_demo_data(session)
        complete_id = _by_title(session, "Export billing history").id
        before = len(
            session.exec(select(Transition).where(Transition.ticket_id == complete_id)).all()
        )

        seed_demo_data(session)
        seed_demo_data(session)

        after = len(
            session.exec(select(Transition).where(Transition.ticket_id == complete_id)).all()
        )
        assert before == after == 4


class TestSeedPreconditions:
    def test_requires_the_uns_system_project(self, session: Session) -> None:
        """Migration 0001 seeds UNS (ADR-0017); seeding without it is a bug."""
        uns = _project(session, "UNS")
        session.delete(uns)
        session.commit()

        with pytest.raises(RuntimeError, match="UNS"):
            seed_demo_data(session)


def test_day_offset_is_naive_midnight() -> None:
    from jackrabbit.seed import _day_offset

    value = _day_offset(3)
    assert value.tzinfo is None, "Sprint columns are NaiveDatetime"
    assert value.date() == date.today() + timedelta(days=3)
